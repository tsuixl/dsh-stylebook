import {test} from 'node:test';
import assert from 'node:assert/strict';
import {readFile} from 'node:fs/promises';
import {runInContext} from 'node:vm';
import {build} from 'esbuild';
import {JSDOM} from 'jsdom';

test('reviewed controls edit the Host bridge, preserve presets and never use localStorage',async()=>{
 const result=await build({entryPoints:['src/client/page.js'],bundle:true,platform:'browser',format:'iife',globalName:'pageModule',write:false});
 const dom=new JSDOM('<div class="stylebook-page"></div>',{runScripts:'outside-only',pretendToBeVisual:true});
 const w=dom.window;w.structuredClone=structuredClone;
 w.matchMedia=()=>Object.assign(new w.EventTarget(),{matches:false});
 Object.defineProperty(w,'localStorage',{get(){throw new Error('Plugin must use Host persistence');}});
 runInContext(result.outputFiles[0].text,dom.getInternalVMContext());
 const defaults=(await import('../src/model/defaults.ts')).defaults;
 let state={config:structuredClone(defaults),selectedPreset:'default',presets:[],writable:true,status:'已保存'};
 const listeners=new Set();let closed=false,saves=0;
 const bridge={snapshot:()=>state,subscribe:f=>{listeners.add(f);return()=>listeners.delete(f);},preview:()=>{},flush:async()=>true,save:async draft=>{saves++;state={...structuredClone(draft),writable:true,status:'已保存'};for(const f of listeners)f();return true;}};
 const root=w.document.querySelector('.stylebook-page');root.innerHTML=await readFile('src/client/view.html','utf8');
 const dispose=w.pageModule.mountPage(root,bridge,()=>{closed=true;});
 assert.equal(root.querySelectorAll('.color-control').length,3);
 const $=id=>root.querySelector('#'+id);
 function input(id,value){$(id).value=value;$(id).dispatchEvent(new w.Event('input',{bubbles:true}));}
 input('code-size','22');assert.equal(state.config.codeSize,22);
 input('hex-sidebar','#ABCDEF');assert.equal(state.config.palettes.light.sidebar,'#abcdef');
 input('hex-theme','#F2F2ED');
 assert.equal(root.style.getPropertyValue('--control'),'#f2f2ed');
 assert.equal(root.style.getPropertyValue('--surface'),'#f2f2ed');
 assert.equal(root.style.getPropertyValue('--subtle'),'#ebecea');
 root.querySelector('[data-mode="dark"]').click();
 assert.equal(root.style.getPropertyValue('--control'),'#292e39');
 root.querySelector('[data-mode="light"]').click();
 assert.equal(root.style.getPropertyValue('--control'),'#f2f2ed');
 $('ui-weight').click();const option=[...root.querySelectorAll('.choice-option')].find(b=>b.textContent==='Medium');option.click();assert.equal(state.config.uiWeight,500);
 root.querySelector('[data-font-role="ui"]').click();input('font-search','Uninstalled Font');root.querySelector('.font-custom').click();assert.equal(state.config.uiFont,'Uninstalled Font');
 $('save-preset').click();$('preset-name').value='我的方案';$('save-form').dispatchEvent(new w.Event('submit',{bubbles:true,cancelable:true}));assert.equal(state.presets.length,1);
 $('reset').click();assert.equal(state.presets.length,1);assert.equal(state.config.codeSize,13);
 $('preset-select').click();[...root.querySelectorAll('.choice-option')].find(b=>b.textContent==='我的方案').click();assert.equal(state.config.codeSize,22);
 $('delete-preset').click();assert.equal(state.presets.length,0);assert.equal(state.config.codeSize,22);
 state.writable=false;for(const listener of listeners)listener();assert.equal($('code-size').disabled,true);assert.equal(root.querySelector('[data-close-settings]').disabled,false);
 root.querySelector('[data-close-settings]').click();await new Promise(setImmediate);assert.equal(closed,true);assert.ok(saves>0);
 dispose();assert.equal(listeners.size,0);dom.window.close();
});
